import 'dart:convert';
import 'dart:io';

import 'package:shenliyuan/legal/legal_documents.dart';
import 'package:shenliyuan/config/app_contacts.dart';

/// 公共页面和 App 使用同一份正文，Go 将导出页面嵌入发布二进制。
void main(List<String> args) {
  final directory =
      Directory.fromUri(Platform.script.resolve('../../server/static/legal/'));
  final check = args.contains('--check');
  final documents = <String, LegalDocument>{
    'terms': LegalDocuments.userAgreement,
    'privacy': LegalDocuments.privacyPolicy,
  };
  var outdated = false;
  const escape = HtmlEscape(HtmlEscapeMode.element);
  for (final entry in documents.entries) {
    final document = entry.value;
    final other = entry.key == 'terms' ? 'privacy' : 'terms';
    final otherTitle = entry.key == 'terms' ? '隐私政策' : '用户协议';
    final edu = entry.key == 'privacy'
        ? '<section id="edu-data-consent"><h2>教务数据专项授权</h2><div class="body">${escape.convert(LegalDocuments.eduDataConsent.body.trim())}</div></section>'
        : '';
    final html = '''<!doctype html>
<!-- Generated by client/tool/export_legal_documents.dart. Edit client/lib/legal/legal_documents.dart. -->
<html lang="zh-CN">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>沈理校园${escape.convert(document.title)}</title>
<style>:root{color-scheme:light dark}body{margin:0;background:Canvas;color:CanvasText;font-family:system-ui,sans-serif;line-height:1.8}main{max-width:760px;margin:32px auto;padding:0 20px 48px}nav{display:flex;flex-wrap:wrap;gap:24px}h1{font-size:1.8rem;line-height:1.4}.version{font-size:.9rem}.body{white-space:pre-wrap;overflow-wrap:anywhere;font:inherit}</style></head>
<body><main><nav aria-label="文档导航"><a href="/">沈理校园首页</a><a href="/$other">$otherTitle</a></nav>
<h1>沈理校园${escape.convert(document.title)}</h1>
<p class="version">文档确认版本：${escape.convert(LegalDocuments.version)}</p>
<div class="body">${escape.convert(document.body.trim())}</div>
$edu
</main></body></html>
''';
    final file = File('${directory.path}/${entry.key}.html');
    if (check) {
      if (!file.existsSync() || file.readAsStringSync() != html) {
        stderr.writeln('公开法律文档与 App 不一致：${file.path}');
        outdated = true;
      }
    } else {
      directory.createSync(recursive: true);
      file.writeAsStringSync(html);
      stdout.writeln('已同步 ${entry.key}.html');
    }
  }
  final extensionSource = File.fromUri(
      Platform.script.resolve('../../browser-extension/store/privacy.txt'));
  final extensionBody = extensionSource.readAsStringSync().trim();
  final extensionHtml = '''<!doctype html>
<!-- Generated by client/tool/export_legal_documents.dart. Edit browser-extension/store/privacy.txt. -->
<html lang="zh-CN"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>沈理校园教务助手隐私说明</title>
<style>:root{color-scheme:light dark}body{margin:0;background:Canvas;color:CanvasText;font-family:system-ui,sans-serif;line-height:1.8}main{max-width:760px;margin:32px auto;padding:0 20px 48px}.body{white-space:pre-wrap;overflow-wrap:anywhere}nav{display:flex;flex-wrap:wrap;gap:24px}</style></head>
<body><main><nav aria-label="文档导航"><a href="/">沈理校园首页</a><a href="/privacy">网站与 App 隐私政策</a></nav>
<h1>沈理校园教务助手隐私说明</h1><div class="body">${escape.convert(extensionBody)}

${escape.convert(AppContacts.legalContactText)}</div></main></body></html>
''';
  final extensionFile = File('${directory.path}/extension-privacy.html');
  if (check) {
    if (!extensionFile.existsSync() ||
        extensionFile.readAsStringSync() != extensionHtml) {
      stderr.writeln('扩展公开隐私说明未同步：${extensionFile.path}');
      outdated = true;
    }
  } else {
    extensionFile.writeAsStringSync(extensionHtml);
    stdout.writeln('已同步 extension-privacy.html');
  }
  if (outdated) exitCode = 1;
}
